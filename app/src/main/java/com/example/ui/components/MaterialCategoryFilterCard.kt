@Composable
fun MaterialCategoryFilterCard(
    selectedCategory: MaterialCategory,
    onCategorySelected: (MaterialCategory) -> Unit,
    modifier: Modifier = Modifier
) {
    Card(
        modifier = modifier
            .fillMaxWidth()
            .border(1.dp, MaterialTheme.colorScheme.outlineVariant, RoundedCornerShape(20.dp))
            .testTag("material_category_filter_card"),
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(imageVector = Icons.Default.FilterList, contentDescription = null, tint = MetaBlue, modifier = Modifier.size(18.dp))
                    Spacer(modifier = Modifier.width(8.dp))
                    Text(
                        text = "MATERIAL CATEGORIES",
                        fontSize = 11.sp,
                        fontFamily = FontFamily.Monospace,
                        fontWeight = FontWeight.Bold,
                        color = MetaBlue
                    )
                }

                Surface(
                    shape = RoundedCornerShape(6.dp),
                    color = MetaBlue.copy(0.12f)
                ) {
                    Text(
                        text = selectedCategory.displayName.uppercase(),
                        fontSize = 9.sp,
                        fontWeight = FontWeight.Bold,
                        color = MetaBlue,
                        modifier = Modifier.padding(horizontal = 8.dp, vertical = 3.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(12.dp))

            // Scrollable Category Tabs
            LazyRow(
                horizontalArrangement = Arrangement.spacedBy(8.dp),
                contentPadding = PaddingValues(horizontal = 2.dp)
            ) {
                items(MaterialCategory.values()) { category ->
                    val isSelected = selectedCategory == category
                    val icon = getMaterialCategoryIcon(category)

                    Surface(
                        shape = RoundedCornerShape(12.dp),
                        color = if (isSelected) MetaBlue else MaterialTheme.colorScheme.surfaceVariant,
                        modifier = Modifier
                            .clickable { onCategorySelected(category) }
                            .testTag("mat_cat_${category.name}")
                    ) {
                        Row(
                            modifier = Modifier.padding(horizontal = 12.dp, vertical = 8.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Icon(
                                imageVector = icon,
                                contentDescription = null,
                                tint = if (isSelected) Color.White else MaterialTheme.colorScheme.onSurfaceVariant,
                                modifier = Modifier.size(14.dp)
                            )
                            Spacer(modifier = Modifier.width(6.dp))
                            Text(
                                text = category.displayName,
                                fontSize = 11.sp,
                                fontWeight = FontWeight.Bold,
                                color = if (isSelected) Color.White else MaterialTheme.colorScheme.onSurface
                            )
                        }
                    }
                }
            }
        }
    }
}

private fun getMaterialCategoryIcon(category: MaterialCategory): ImageVector {
    return when (category) {
        MaterialCategory.ALL -> Icons.Default.Category
        MaterialCategory.CONCRETE -> Icons.Default.WaterDrop
        MaterialCategory.REBAR_STEEL -> Icons.Default.Category
        MaterialCategory.PIPING_MEP -> Icons.Default.Plumbing
        MaterialCategory.CHEMICALS -> Icons.Default.Science
        MaterialCategory.FASTENERS -> Icons.Default.Category
        MaterialCategory.ELECTRICAL -> Icons.Default.ElectricalServices
    }
}
